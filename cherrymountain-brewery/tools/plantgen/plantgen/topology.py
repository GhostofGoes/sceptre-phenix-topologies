"""The phenix topology file of each site of the fleet.

A node of a site is the node of the same host in today's hand-written modules
(phenix-configs/topology-core.yml, -soc.yml, and -remote-access.yml): its
hardware, image, injections, and commands. What names a host or an address of
the plant follows the site's plant description (`fleet.site_plant`). The
site-profiles spike (spikes/site-profiles, `site_nodes`) built such nodes as a
probe.

What each field of a node becomes:

- `general.hostname`, `delay.c2`: the site's name of the host. A host that
  the site does not have is not waited for.
- `general.description` and the `description` of an injection: prose, so
  `fleet.prose` gives their hostnames the site's prefix. These are the only
  fields whose text is rewritten.
- `network.interfaces`: built again from the description: the name, the VLAN
  alias, the address, the mask, and the gateway. `dns` follows the name server
  of the hand-written node (see `_name_server`).
- `network.routes`: built again from the site's networks (see `static_routes`).
- `network.rulesets`: none. A router gets its rulesets from the `vrouter` app
  of the site's scenario (`scenario-site-<code>.yml`), which netcheck writes
  (tools/netcheck, `netcheck.sitegen`).
- `labels`: `zone` is the host's first network, as in the hand-written
  modules, and a router keeps its own label. `site` is new: the site's code.
- `annotations`: a forwarded port of the head node moves by the site's index
  (see `_tunnel`).
- `hardware`, `type`, `commands`, and the `src`, `dst`, and `permissions` of
  an injection: as they are. A path names a file under phenix-injects
  (`bbmd/ot-svc.env`, `openplc/full/plc-cellar.zip`), not a host of the site.
  The content of those files is still the single site's.
"""

from __future__ import annotations

import copy
import ipaddress
from pathlib import Path
from typing import Any, Final

import yaml

from plantgen import fleet, sites
from plantgen.model import HostSpec, PlantError, PlantFile
from plantgen.sites import SiteSpec

#: The hand-written modules that hold today's nodes, in boot order.
MODULES: Final[tuple[str, ...]] = ("core", "soc", "remote-access")
#: The node types whose interfaces are named eth0, eth1, ... like the VyOS NICs.
ROUTER_TYPES: Final[frozenset[str]] = frozenset({"Router", "Firewall"})
#: The annotation of the ports that the head node forwards to a VM.
AUTOTUNNEL: Final[str] = "phenix/startup-autotunnel"
#: A site's forwarded ports are this far from those of the site before it.
TUNNEL_STEP: Final[int] = 100
#: The VLAN whose hosts a site with one firewall moves to its plant network.
#: The sensor of such a site is on that network (PLANS.md, section 4.6).
OPS_VLAN: Final[str] = "OPS"
#: The network sensor. No image exists yet: the name, the size (decision D19:
#: 4 vCPUs, 16 GB), and the host number are those of the site-profiles spike.
SENSOR_NAME: Final[str] = "sensor"
SENSOR_IMAGE: Final[str] = "cm-sensor.qc2"
SENSOR_VCPUS: Final[int] = 4
SENSOR_MEMORY_MB: Final[int] = 16384
SENSOR_HOST_NUMBER: Final[int] = 60

#: The name of a site's file under phenix-configs.
FILE_NAME: Final[str] = "topology-site-{code}.yml"

HEADER: Final[str] = """\
# cherrymountain-site-{code}: the nodes of the site `{code}` ({title}).
# Generated by plantgen from plant/plant.yaml and plant/sites.yaml (site {code}),
# with the nodes of topology-core.yml, topology-soc.yml, and
# topology-remote-access.yml as the source of each node. Do not edit.
#
# The firewall rulesets are not here. They are in scenario-site-{code}.yml,
# which netcheck writes (tools/netcheck): the rules of the conduits whose two
# ends are hosts of this site.
#
# This file is not a finished site. It does not have these parts yet:
# - The edge's WAN side: its default route, NAT, and the VPN, which the WAN
#   generator writes (tools/wangen).
# - The conduits between sites, with their rules, and a whole scenario. The
#   injected files still hold the names and addresses of the single site.
"""


def file_name(site: SiteSpec) -> str:
    """The name of the site's file under phenix-configs."""
    return FILE_NAME.format(code=site.code)


def load_nodes(directory: Path) -> dict[str, dict[str, Any]]:
    """Today's nodes by hostname, from the hand-written modules in `directory`."""
    nodes: dict[str, dict[str, Any]] = {}
    for module in MODULES:
        path = directory / f"topology-{module}.yml"
        if not path.is_file():
            raise PlantError(f"{path} does not exist; a site's nodes come from it")
        doc: dict[str, Any] = yaml.safe_load(path.read_text(encoding="utf-8"))
        for node in doc["spec"]["nodes"]:
            name: str = node["general"]["hostname"]
            if name in nodes:
                raise PlantError(f"{path.name}: {name} is a node of two modules")
            nodes[name] = node
    return nodes


def render(
    site: SiteSpec, plant: PlantFile, doc: PlantFile, nodes: dict[str, dict[str, Any]]
) -> str:
    """The text of the site's topology file."""
    # Block style only, as for the app blocks: prek enforces it with yamllint.
    body = yaml.safe_dump(
        site_topology(site, plant, doc, nodes),
        sort_keys=True,
        default_flow_style=False,
        width=1000,
    )
    return HEADER.format(code=site.code, title=site.title) + body


def site_topology(
    site: SiteSpec, plant: PlantFile, doc: PlantFile, nodes: dict[str, dict[str, Any]]
) -> dict[str, Any]:
    """The site's Topology config.

    `plant` is plant.yaml, `doc` is the site's plant description, and `nodes`
    are today's nodes (`load_nodes`). The nodes keep the order of the modules,
    which is boot order. The sensor is last.
    """
    try:
        hosts = [name for name in nodes if site.host(name) in doc.hosts]
        missing = sorted(set(doc.hosts) - {site.host(name) for name in hosts})
        if missing:
            raise PlantError(f"no hand-written module has a node for {missing}")
        made = [_node(site, plant, doc, name, nodes[name]) for name in hosts]
        if site.sensor:
            made.append(sensor_node(site, doc))
    except PlantError as exc:
        raise PlantError(f"site {site.code}: topology: {exc}") from exc
    return {
        "apiVersion": "phenix.sandia.gov/v1",
        "kind": "Topology",
        "metadata": {"name": f"cherrymountain-site-{site.code}"},
        "spec": {"nodes": made},
    }


def _node(
    site: SiteSpec, plant: PlantFile, doc: PlantFile, plain: str, source: dict[str, Any]
) -> dict[str, Any]:
    """The node of the host `plain` at the site."""
    name = site.host(plain)
    host = doc.hosts[name]
    router = source["type"] in ROUTER_TYPES
    node = copy.deepcopy(source)
    stamp = fleet.prose(site, plant.hosts)
    general = node["general"]
    general["hostname"] = name
    for described in (general, *node.get("injections", [])):
        if "description" in described:
            described["description"] = stamp(described["description"])
    waits = [
        {**wait, "hostname": site.host(wait["hostname"])}
        for wait in node.get("delay", {}).get("c2", [])
        if site.host(wait["hostname"]) in doc.hosts
    ]
    node.pop("delay", None)
    if waits:
        node["delay"] = {"c2": waits}
    annotations = node.get("annotations", {})
    if AUTOTUNNEL in annotations:
        annotations[AUTOTUNNEL] = [
            _tunnel(site, name, entry) for entry in annotations[AUTOTUNNEL]
        ]
    servers = {
        interface["name"]: interface["dns"]
        for interface in source.get("network", {}).get("interfaces", [])
        if "dns" in interface
    }
    interfaces = []
    for number, (key, interface) in enumerate(host.interfaces.items()):
        address, mask = interface.ip.split("/")
        entry: dict[str, Any] = {
            "name": f"eth{number}" if router else key,
            "type": "ethernet",
            "proto": "static",
            "vlan": interface.vlan,
            "address": address,
            "mask": int(mask),
        }
        gateway = None if router else _gateway(doc, name, interface.vlan)
        if gateway is not None:
            entry["gateway"] = gateway
        found = [
            _name_server(site, plant, doc, name, server=server, gateway=gateway)
            for server in servers.get(key, [])
        ]
        if any(found):
            entry["dns"] = [server for server in found if server]
        interfaces.append(entry)
    network: dict[str, Any] = {"interfaces": interfaces}
    routes = static_routes(doc, name, host, router)
    if routes:
        network["routes"] = routes
    # `rulesets` and anything else under `network` is left behind on purpose.
    node["network"] = network
    first = next(iter(host.interfaces.values()), None)
    labels: dict[str, str] = dict(node.get("labels", {}))
    if not router and first is not None:
        labels["zone"] = _zone(site, first.vlan)
    labels["site"] = site.code
    node["labels"] = labels
    return node


def _zone(site: SiteSpec, vlan: str) -> str:
    """The zone label of a VLAN alias: the alias without the site, in small letters."""
    return vlan.removeprefix(f"{site.code.upper()}-").lower()


def _address(doc: PlantFile, host: str, vlan: str) -> str | None:
    """The address of `host` on the VLAN, when it is on it."""
    for interface in doc.hosts[host].interfaces.values():
        if interface.vlan == vlan:
            return interface.ip.split("/")[0]
    return None


def _gateway(doc: PlantFile, host: str, vlan: str) -> str | None:
    """The address of the VLAN's router, for a host that is not that router."""
    network = doc.networks.get(vlan)
    if network is None or network.gateway is None or network.gateway == host:
        return None
    return _address(doc, network.gateway, vlan)


def _name_server(
    site: SiteSpec,
    plant: PlantFile,
    doc: PlantFile,
    host: str,
    *,
    server: str,
    gateway: str | None,
) -> str | None:
    """The name server of an interface, for the address `server` of today's node.

    The address is that of a host of plant.yaml, and the site's host of the
    same name has the site's address. Two cases have no such host:

    - The site left the server out (the pub has no ot-svc). The host then asks
      its gateway, because the firewall forwards names there (PLANS.md 4.6).
    - The server is a host of the internet (the office PC asks inet-traffic).
      Its address in the fleet is not in sites.yaml or wan.yaml, so the
      interface gets no name server. The single site's address must not stay:
      203.0.113.10 is the uplink of `fc` in the fleet.
    """
    owner = next(
        (
            (name, key)
            for name, spec in plant.hosts.items()
            for key, interface in spec.interfaces.items()
            if interface.ip.split("/")[0] == server
        ),
        None,
    )
    if owner is None:
        raise PlantError(f"{host}: its name server {server} is no host of plant.yaml")
    name, key = owner
    if name in sites.SHARED_HOSTS:
        return None
    if site.host(name) not in doc.hosts:
        return gateway
    return doc.hosts[site.host(name)].interfaces[key].ip.split("/")[0]


def static_routes(
    doc: PlantFile, name: str, host: HostSpec, router: bool
) -> list[dict[str, str]]:
    """The static routes of a host, from the site's networks.

    A network can have a second router on it that is not its gateway: the DMZ
    has both firewalls. Through that router, a host of the network reaches the
    networks that the router is the gateway of. This gives the edge firewall
    and the DMZ hosts their routes to the zones behind the OT firewall. A
    router that is on a network of another gateway takes its default route
    there: the OT firewall, through the edge.

    The vendor's WireGuard gateway is the way to the tunnel's network for the
    host that the vendor reaches (the jump host).

    Not here: the edge's default route and its routes to other sites. The WAN
    generator writes them. A site with one firewall has no static route.
    """
    routes: list[dict[str, str]] = []
    mine = list(dict.fromkeys(i.vlan for i in host.interfaces.values()))
    for vlan in mine:
        network = doc.networks.get(vlan)
        if network is None:
            continue
        for other in sorted(_routers(doc) - {name}):
            via = _address(doc, other, vlan)
            if via is None:
                continue
            if network.gateway == other:
                if router:
                    routes.append({"destination": "0.0.0.0/0", "next": via})
                continue
            routes += [
                {"destination": behind.subnet, "next": via}
                for alias, behind in doc.networks.items()
                if behind.gateway == other and alias not in mine
            ]
    tunnel = doc.wireguard
    if tunnel is not None and tunnel.server != name:
        reached = {ipaddress.ip_interface(net).ip for net in tunnel.client_allowed_ips}
        for interface in host.interfaces.values():
            via = _address(doc, tunnel.server, interface.vlan)
            if ipaddress.ip_interface(interface.ip).ip in reached and via is not None:
                inside = ipaddress.ip_interface(tunnel.server_address).network
                routes.append({"destination": str(inside), "next": via})
    return sorted(routes, key=lambda route: ipaddress.ip_network(route["destination"]))


def _routers(doc: PlantFile) -> set[str]:
    """The routers of the site: the hosts that a network names as its gateway."""
    return {
        network.gateway
        for network in doc.networks.values()
        if network.gateway is not None
    }


def _tunnel(site: SiteSpec, host: str, entry: str) -> str:
    """A forwarded port, `<port of the head node>:<port of the VM>`, for the site.

    Every site has a SCADA server that asks for port 11881 of the head node,
    and one experiment can give it to one VM. So the head node's port moves by
    100 for each step of the site's index: `fr` keeps 11881, and `ep` (index
    2) gets 12081.
    """
    outside, colon, inside = entry.partition(":")
    if not colon or not outside.isdigit():
        raise PlantError(f"{host}: cannot read the forwarded port {entry!r}")
    return f"{int(outside) + TUNNEL_STEP * site.index}:{inside}"


def sensor_node(site: SiteSpec, doc: PlantFile) -> dict[str, Any]:
    """The site's network sensor (PLANS.md, sections 4.1 and 4.6).

    It is a stand-in until a sensor image exists. At a site with two firewalls
    it is in the SOC zone, which has no other host there. At a site with one
    firewall it is in the plant network, where the OPS hosts are. The mirror
    app adds its mirror interface.
    """
    vlan = site.vlan(fleet.SENSOR_VLAN)
    if vlan not in doc.networks:
        move = site.moves.get(OPS_VLAN)
        if move is None:
            raise PlantError(
                f"the site has a sensor, and no {vlan} network and no move of "
                f"{OPS_VLAN} to put it on"
            )
        vlan = site.vlan(move.vlan)
    subnet = ipaddress.ip_network(doc.networks[vlan].subnet)
    address = str(subnet.network_address + SENSOR_HOST_NUMBER)
    name = site.host(SENSOR_NAME)
    for other, spec in doc.hosts.items():
        taken = {leg.ip.split("/")[0] for leg in spec.interfaces.values()}
        if other == name or address in taken:
            raise PlantError(
                f"the sensor's name or its address {address} is taken by {other}"
            )
    interface: dict[str, Any] = {
        "name": "IF0",
        "type": "ethernet",
        "proto": "static",
        "vlan": vlan,
        "address": address,
        "mask": subnet.prefixlen,
    }
    gateway = _gateway(doc, name, vlan)
    if gateway is not None:
        interface["gateway"] = gateway
    return {
        "type": "VirtualMachine",
        "general": {
            "hostname": name,
            "description": "Network sensor (a stand-in: no sensor image exists yet)",
        },
        "hardware": {
            "os_type": "linux",
            "vcpus": SENSOR_VCPUS,
            "memory": SENSOR_MEMORY_MB,
            "drives": [{"image": SENSOR_IMAGE}],
        },
        "labels": {"zone": _zone(site, vlan), "site": site.code},
        "network": {"interfaces": [interface]},
    }
