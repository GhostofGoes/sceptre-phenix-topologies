def _tag_base(t: Tag) -> dict[str, Any]:
    d: dict[str, Any] = {"name": t.name, "desc": t.desc, "type": t.type}
    if t.units:
        d["units"] = t.units
    if t.range:
        d["range"] = list(t.range)
    if is_analog(t.type):
        d["scaling"] = t.scaling
    return d


def tags_doc(plant: Plant, alloc: Allocation) -> dict[str, Any]:
    """Expanded tag database, including generated alarm bits."""
    tags = []
    for t in plant.tags:
        d = _tag_base(t)
        d.update({"area": t.area, "unit": t.unit, "source": t.source, "plc": t.plc})
        if t.device:
            d.update(
                {
                    "rio": t.rio,
                    "federate": t.federate,
                    "device": t.device.name,
                    "device_type": t.device.type,
                    "point": t.point,
                    "helics_key": t.helics_key,
                }
            )
        if t.plc is None:
            d["owner"] = t.owner
        if t.signed:
            d["signed"] = True
        if t.written_by:
            d["written_by"] = t.written_by
        if t.bacnet:
            d["bacnet"] = t.bacnet.model_dump(exclude_none=True)
        if t.generated:
            d["generated"] = True
        if t.alarms:
            d["alarms"] = [a.name for a in t.alarms]
        tags.append(d)
    return {"generator": GENERATOR, "variant": plant.variant, "tags": tags}


class RegisterRow(BaseModel):
    """One tag in every addressing convention (DESIGN.md §12.5)."""

    tag: str
    type: str
    units: str | None
    scaling: int | None
    rio: str | None
    rio_space: str | None
    otsim_register: int | None  # ot-sim literal register number = PDU address
    master_fc: int | None  # OpenPLC modbus_master function code
    master_offset: int | None  # OpenPLC modbus_master PDU offset
    plc: str
    plc_iec: str
    slave_space: str
    slave_read_fc: int
    slave_pdu_address: int  # OpenPLC modbus_slave, 0-based
    fuxa_memaddress: str
    fuxa_address: int  # FUXA, 1-based
    scada_access: str

    @classmethod
    def of(cls, a: TagAddress) -> RegisterRow:
        """Build the row for one allocated tag."""
        t = a.tag
        return cls(
            tag=t.name,
            type=t.type,
            units=t.units,
            scaling=t.scaling if is_analog(t.type) else None,
            rio=t.rio,
            rio_space=a.rio_space,
            otsim_register=a.rio_address,
            master_fc=a.master_fc,
            master_offset=a.rio_address,
            plc=t.plc,
            plc_iec=str(a.plc_iec),
            slave_space=a.slave_space,
            slave_read_fc=READ_FC[a.slave_space],
            slave_pdu_address=a.slave_address,
            fuxa_memaddress=a.fuxa_memaddress,
            fuxa_address=a.fuxa_address,
            scada_access=access(t),
        )


def register_rows(plant: Plant, alloc: Allocation) -> list[RegisterRow]:
    """Register rows in tag order (PLC tags only; BACnet points have none)."""
    return [RegisterRow.of(alloc.tags[t.name]) for t in plant.tags if t.plc]


def registers_doc(plant: Plant, alloc: Allocation) -> dict[str, Any]:
    """Register map in all addressing conventions, one row per tag."""
    rows = [r.model_dump() for r in register_rows(plant, alloc)]
    return {
        "generator": GENERATOR,
        "variant": plant.variant,
        "conventions": {
            "otsim_register": "ot-sim literal register number; equals the PDU address "
            "(coil 1.., discrete 10001.., input 30001.., holding 40001..)",
            "master_offset": "OpenPLC modbus_master PDU offset (= otsim_register)",
            "plc_iec": "IEC 61131-3 located variable in the PLC",
            "slave_pdu_address": "OpenPLC v4 modbus_slave PDU address (0-based); "
            "holding registers are %QW, then %MW (at qw_count), then %MD, then %ML "
            "(see slave_layouts)",
            "fuxa_address": "FUXA 1-based address (FUXA subtracts 1) within memaddress",
        },
        "slave_layouts": {
            plc: layout.buffer_mapping() for plc, layout in alloc.layouts.items()
        },
        "registers": rows,
    } | _extra_registers(plant, alloc)


def _extra_registers(plant: Plant, alloc: Allocation) -> dict[str, Any]:
    """Sections that only variants with such devices have."""
    extra: dict[str, Any] = {}
    northbound = {plc: plant.hosts[plc].northbound for plc in alloc.plc_rios}
    if set(northbound.values()) != {"modbus"}:
        extra["northbound"] = northbound
    if alloc.bacnet:
        extra["bacnet_objects"] = [
            _bacnet_row(plant, o) for objs in alloc.bacnet.values() for o in objs
        ]
    return extra


def _bacnet_row(plant: Plant, o: BacnetObject) -> dict[str, Any]:
    ep = plant.hosts[o.host].bacnet
    return {
        "tag": o.tag.name if o.tag else None,
        "host": o.host,
        "device_instance": ep.instance if ep else None,
        "object_type": o.object_type,
        "object_type_number": o.type_number,
        "instance": o.instance,
        "fuxa_address": o.fuxa_address,
        "helics_key": f"{o.device.topic}.{o.point}",
    }


def registers_csv(plant: Plant, alloc: Allocation) -> str:
    """CSV view of :func:`registers_doc`."""
    rows = [
        {k: "" if v is None else v for k, v in r.model_dump().items()}
        for r in register_rows(plant, alloc)
    ]
    buf = io.StringIO()
    writer = csv.DictWriter(
        buf, fieldnames=list(RegisterRow.model_fields), lineterminator="\n"
    )
    writer.writeheader()
    writer.writerows(rows)
    return buf.getvalue()


