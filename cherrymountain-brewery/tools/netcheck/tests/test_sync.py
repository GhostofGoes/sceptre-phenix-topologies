"""sync.py: embedding generated app blocks into a scenario."""

from __future__ import annotations

from pathlib import Path

import pytest
import sync
import yaml

SCENARIO = """apiVersion: phenix.sandia.gov/v2
kind: Scenario
metadata:
  name: t
  annotations:
    topology: t
spec:
  apps:
  - name: startup
  # sync:begin ot-sim
  # placeholder
  # sync:end ot-sim
  # sync:begin helics
  # placeholder
  # sync:end helics
  # sync:begin soh overlay
  - name: soh
    metadata:
      testReachability: 'off'
      hostListeners:
        a:
        - ':1'
  # sync:end soh
"""

OTSIM = """# Generated by plantgen from plant/plant.yaml (variant t). Do not edit.
name: ot-sim
metadata:
  infrastructure: brewery
hosts:
- hostname: rio
  metadata:
    type: fd-server
"""

SOH = """# Generated by plantgen from plant/plant.yaml (variant t). Do not edit.
name: soh
metadata:
  testReachability: 'off'
  hostListeners:
    a:
    - ':1'
    - ':2'
    b:
    - ':3'
  testCustomReachability:
  - src: a
    dst: b|IF0
    proto: tcp
    port: 1
    wait: 5m
"""


@pytest.fixture
def variant(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> sync.Variant:
    monkeypatch.setattr(sync, "ROOT", tmp_path)
    scenario: Path = tmp_path / "scenario-t.yml"
    scenario.write_text(SCENARIO)
    generated: Path = tmp_path / "plant" / "generated" / "t"
    (generated / "phenix").mkdir(parents=True)
    return sync.Variant(name="t", scenario=scenario, generated=generated)


def apps(v: sync.Variant) -> dict[str, dict]:
    doc = yaml.safe_load(v.scenario.read_text())
    return {a["name"]: a for a in doc["spec"]["apps"]}


def test_missing_generated_blocks_are_skipped(
    variant: sync.Variant, capsys: pytest.CaptureFixture[str]
) -> None:
    assert sync.sync_scenario(variant, check=True) == []
    out: str = capsys.readouterr().out
    assert "skip t/ot-sim" in out
    assert "plantgen has not emitted" in out
    assert sync.sync_scenario(variant, check=False) == []
    assert "ot-sim" not in apps(variant)  # the placeholder stays


def test_a_generated_block_is_embedded_verbatim(variant: sync.Variant) -> None:
    (variant.phenix_dir / "ot-sim.yaml").write_text(OTSIM)
    assert sync.sync_scenario(variant, check=True) == [
        "scenario-t.yml: app ot-sim differs from plant/generated/t/phenix/ot-sim.yaml"
    ]
    assert sync.sync_scenario(variant, check=False) == []
    assert apps(variant)["ot-sim"] == yaml.safe_load(OTSIM)
    assert sync.sync_scenario(variant, check=True) == []
    text: str = variant.scenario.read_text()
    assert "  - name: ot-sim\n    metadata:\n      infrastructure: brewery\n" in text


def test_a_changed_block_is_stale_until_synced(variant: sync.Variant) -> None:
    (variant.phenix_dir / "ot-sim.yaml").write_text(OTSIM)
    sync.sync_scenario(variant, check=False)
    (variant.phenix_dir / "ot-sim.yaml").write_text(OTSIM.replace("brewery", "plant"))
    assert sync.sync_scenario(variant, check=True) != []
    sync.sync_scenario(variant, check=False)
    assert apps(variant)["ot-sim"]["metadata"]["infrastructure"] == "plant"


def test_a_block_without_a_marker_is_reported(variant: sync.Variant) -> None:
    (variant.phenix_dir / "ntp.yaml").write_text("name: ntp\nhosts: []\n")
    problems: list[str] = sync.sync_scenario(variant, check=True)
    assert problems == [
        "scenario-t.yml: no sync:begin ntp marker for plant/generated/t/phenix/ntp.yaml"
    ]


def test_soh_is_merged_not_replaced(variant: sync.Variant) -> None:
    (variant.phenix_dir / "soh.yaml").write_text(SOH)
    assert sync.sync_scenario(variant, check=True) != []
    assert sync.sync_scenario(variant, check=False) == []
    soh: dict = apps(variant)["soh"]["metadata"]
    assert soh["hostListeners"] == {"a": [":1", ":2"], "b": [":3"]}
    assert soh["testCustomReachability"][0]["dst"] == "b|IF0"
    # Merging again changes nothing.
    assert sync.sync_scenario(variant, check=True) == []
    before: str = variant.scenario.read_text()
    sync.sync_scenario(variant, check=False)
    assert variant.scenario.read_text() == before


def test_app_order_is_checked(variant: sync.Variant) -> None:
    text: str = variant.scenario.read_text()
    variant.scenario.write_text(
        text.replace("  # sync:begin ot-sim", "  - name: helics\n  # sync:begin ot-sim")
    )
    (variant.phenix_dir / "ot-sim.yaml").write_text(OTSIM)
    sync.sync_scenario(variant, check=False)
    assert sync.sync_scenario(variant, check=True) == [
        "scenario-t.yml: apps must be ordered ot-sim, cherrymountain, helics"
    ]


def test_unbalanced_markers_are_reported(variant: sync.Variant) -> None:
    variant.scenario.write_text(SCENARIO.replace("  # sync:end ot-sim\n", ""))
    problems: list[str] = sync.sync_scenario(variant, check=True)
    assert len(problems) == 1
    assert "sync:begin" in problems[0]


def test_the_repository_is_in_sync() -> None:
    assert sync.main(["--check"]) == 0


def test_an_lfs_pointer_skips_the_zip_check(
    variant: sync.Variant,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    pointer: Path = tmp_path / "plc-cellar.zip"
    pointer.write_text(
        "version https://git-lfs.github.com/spec/v1\n"
        "oid sha256:4a41e52741840bb54d2c6a42b30fcf0f965d8cdd608740788580e43fed70de5b\n"
        "size 101270\n"
    )
    monkeypatch.setattr(sync, "PLC_ZIP", pointer)
    assert sync.is_lfs_pointer(pointer)
    assert sync.check_zip(variant) == []
    assert "Git LFS pointer" in capsys.readouterr().out


def test_a_bad_zip_is_not_taken_for_a_pointer(
    variant: sync.Variant, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    bad: Path = tmp_path / "plc-cellar.zip"
    bad.write_bytes(b"PK not really")
    monkeypatch.setattr(sync, "PLC_ZIP", bad)
    assert not sync.is_lfs_pointer(bad)
    with pytest.raises(Exception, match="zip"):
        sync.check_zip(variant)
