"""The phenix workflow file of each site of the fleet.

`phenix workflow apply -c phenix-site-<code>.yml` makes one experiment of a
site alone: the site's topology file, its scenario, a VLAN ID for every VLAN
alias of the topology, and a bridge of the site's own.

The VLAN IDs are the fleet's plan (docs/multisite/PLANS.md, section 3), so a
site keeps its IDs when the four sites and the internet become one experiment:

- A site has a hundred of its own: 100 for the first site, 200 for the next.
- A zone that the single-site plan has keeps that plan's last two digits
  (`OPS` is 106 there, so `EP-OPS` is 306).
- A zone that the single-site plan does not have takes the next ID from 20 up
  in the site's hundred, in the order of the aliases (`EP-CTRL-BH` is 320).
- An access link to an ISP takes 500 and up, in the order of the links in
  wan/wan.yaml.

The WAN generator (tools/wangen, `phenix.vlans`) gives the access links and one
zone of each site an ID too. A test compares the two through the committed
`phenix-wan.yml`.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Final

import yaml

from plantgen.model import PlantError
from plantgen.sites import SiteSpec

#: The name of a site's workflow file, next to phenix.yml.
FILE_NAME: Final[str] = "phenix-site-{code}.yml"
#: The single-site workflow, whose VLAN IDs a site's zones follow.
SINGLE_SITE: Final[str] = "phenix.yml"
#: The fleet's range (PLANS.md, section 3; tools/wangen has the same).
VLAN_RANGE: Final[tuple[int, int]] = (100, 599)
#: The number of IDs of one site.
SITE_SPAN: Final[int] = 100
#: Where the zones start that the single-site plan does not have.
OWN_ZONES: Final[int] = 20
#: The first ID of the access links (a site's edge to an ISP).
ACCESS_BASE: Final[int] = 500
#: phenix lets one stored experiment use a bridge other than `phenix`, so each
#: workflow has its own. A Linux interface name has at most 15 characters.
BRIDGE: Final[str] = "cherrymtn-{code}"
MAX_BRIDGE_NAME: Final[int] = 15

HEADER: Final[str] = """\
# Workflow for the site `{code}` alone: {title}.
# It has the site's topology file and its scenario, with no internet and no
# other site. Apply it with its own branch, so that it maps to its own
# experiment (DESIGN.md 15.1):
#   docker exec phenix phenix workflow apply \\
#     -b cherrymountain-site-{code} -c phenix-site-{code}.yml \\
#     /phenix/topologies/cherrymountain-brewery
# The VLAN IDs are the fleet's (docs/multisite/PLANS.md, section 3): the site
# has the IDs from {low} to {high}, and its access links to the ISPs take
# {access} and up. The bridge is the site's own, because phenix lets only one
# stored experiment use a bridge other than `phenix`.
#
# Generated by plantgen from plant/sites.yaml, wan/wan.yaml, and the VLAN IDs
# of phenix.yml. Do not edit: run `python -m plantgen` in tools/plantgen.
"""


def file_name(site: SiteSpec) -> str:
    """The name of the site's workflow file."""
    return FILE_NAME.format(code=site.code)


def bridge(site: SiteSpec) -> str:
    """The name of the site's bridge."""
    name = BRIDGE.format(code=site.code)
    if len(name) > MAX_BRIDGE_NAME:
        raise PlantError(
            f"site {site.code}: the bridge name {name} is longer than "
            f"{MAX_BRIDGE_NAME} characters"
        )
    return name


def load_single_site(path: Path) -> dict[str, int]:
    """The VLAN IDs of the single-site plan, from its workflow file."""
    if not path.is_file():
        raise PlantError(f"{path} does not exist; a site's VLAN IDs follow it")
    doc: dict[str, Any] = yaml.safe_load(path.read_text(encoding="utf-8"))
    vlans: dict[str, int] = dict((doc.get("spec") or {}).get("vlans") or {})
    if not vlans:
        raise PlantError(f"{path} pins no VLAN ID")
    return vlans


def access_links(wan: dict[str, Any]) -> dict[str, int]:
    """The ID of each access link of wan.yaml, by its VLAN alias.

    An access link joins a site's edge to an ISP. The alias and the order are
    the WAN generator's (tools/wangen, `link_vlan` and `vlans`).
    """
    edges = set(wan["site_blocks"])
    short = {router["name"]: router["short"] for router in wan["routers"]}
    ids: dict[str, int] = {}
    for link in wan["links"]:
        if link["a"] in edges or link["b"] in edges:
            alias = f"WAN-{short[link['a']]}-{short[link['b']]}".upper()
            ids[alias] = ACCESS_BASE + len(ids)
    return ids


def vlan_ids(
    site: SiteSpec, aliases: set[str], single: dict[str, int], wan: dict[str, Any]
) -> dict[str, int]:
    """The ID of every VLAN alias of the site's topology, in the order of the IDs.

    `single` is the single-site plan (`load_single_site`) and `wan` is
    wan/wan.yaml.
    """
    links = access_links(wan)
    base = SITE_SPAN * (site.index + 1)
    prefix = f"{site.code.upper()}-"
    ids: dict[str, int] = {}
    own: list[str] = []
    for alias in sorted(aliases):
        if alias in links:
            ids[alias] = links[alias]
        elif not alias.startswith(prefix):
            raise PlantError(
                f"site {site.code}: the VLAN {alias} is not an access link of "
                f"wan.yaml and does not start with {prefix}, so it has no ID"
            )
        elif alias.removeprefix(prefix) in single:
            ids[alias] = base + single[alias.removeprefix(prefix)] % SITE_SPAN
        else:
            own.append(alias)
    for number, alias in enumerate(own):
        ids[alias] = base + OWN_ZONES + number
    low, high = VLAN_RANGE
    for alias, number in ids.items():
        if alias not in links and not base < number < base + SITE_SPAN:
            raise PlantError(
                f"site {site.code}: the VLAN {alias} gets the ID {number}, "
                f"outside the site's {base + 1} to {base + SITE_SPAN - 1}"
            )
        if not low <= number <= high:
            raise PlantError(
                f"site {site.code}: the VLAN {alias} gets the ID {number}, "
                f"outside the fleet's {low} to {high}"
            )
    by_id: dict[int, str] = {}
    for alias, number in ids.items():
        if number in by_id:
            raise PlantError(
                f"site {site.code}: the VLANs {by_id[number]} and {alias} both "
                f"get the ID {number}"
            )
        by_id[number] = alias
    return dict(sorted(ids.items(), key=lambda item: item[1]))


def site_workflow(
    site: SiteSpec, aliases: set[str], single: dict[str, int], wan: dict[str, Any]
) -> dict[str, Any]:
    """The site's Workflow config. `aliases` are the VLANs of its topology."""
    low, high = VLAN_RANGE
    name = f"cherrymountain-site-{site.code}"
    return {
        "apiVersion": "phenix.sandia.gov/v0",
        "kind": "Workflow",
        "metadata": {},
        "spec": {
            "auto": {"create": "${BRANCH_NAME}", "update": True, "restart": True},
            "topology": name,
            "scenario": name,
            "vlans": vlan_ids(site, aliases, single, wan),
            "vlanRange": {"min": low, "max": high},
            "defaultBridge": bridge(site),
        },
    }


def render(
    site: SiteSpec, aliases: set[str], single: dict[str, int], wan: dict[str, Any]
) -> str:
    """The text of the site's workflow file."""
    body = yaml.safe_dump(
        site_workflow(site, aliases, single, wan),
        sort_keys=False,
        default_flow_style=False,
        width=1000,
    )
    base = SITE_SPAN * (site.index + 1)
    header = HEADER.format(
        code=site.code,
        title=site.title,
        low=base + 1,
        high=base + SITE_SPAN - 1,
        access=ACCESS_BASE,
    )
    return header + body
