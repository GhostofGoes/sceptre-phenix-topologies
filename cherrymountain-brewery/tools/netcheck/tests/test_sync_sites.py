"""sync.py on the sites of the fleet: it writes a site's whole scenario and
copies the site's own injected files."""

from __future__ import annotations

import shutil
from pathlib import Path
from typing import Any

import pytest
import sync
import yaml
from conftest import ROOT

CODES: list[str] = ["fr", "ep", "cs", "fc"]


@pytest.fixture
def fleet(tree: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """The copy of the configs and injects, with what a site is made from."""
    for rel in ("plant/plant.yaml", "plant/sites.yaml", "wan/wan.yaml"):
        (tree / rel).parent.mkdir(exist_ok=True)
        shutil.copy(ROOT / rel, tree / rel)
    shutil.copytree(ROOT / "plant" / "generated" / "fleet", tree / "plant" / "generated" / "fleet")
    monkeypatch.setattr(sync, "ROOT", tree)
    return tree


def problems(site: sync.Site, check: bool = True) -> list[str]:
    return sync.sync_site_copies(site, check) + sync.sync_site_scenario(site, check)


def apps(site: sync.Site) -> dict[str, dict[str, Any]]:
    doc: dict[str, Any] = yaml.safe_load(site.scenario.read_text(encoding="utf-8"))
    return {app["name"]: app for app in doc["spec"]["apps"]}


def test_the_sites_are_those_of_sites_yaml(fleet: Path) -> None:
    found: dict[str, sync.Site] = sync.sites()
    assert list(found) == CODES
    assert found["fc"].scenario == fleet / "phenix-configs" / "scenario-site-fc.yml"
    assert found["fc"].injects == fleet / "phenix-injects" / "fleet" / "fc"
    (fleet / "plant" / "sites.yaml").unlink()
    assert sync.sites() == {}


@pytest.mark.parametrize("code", CODES)
def test_the_committed_site_is_in_sync(fleet: Path, code: str) -> None:
    assert problems(sync.sites()[code]) == []


def test_a_scenario_holds_plantgens_blocks_and_netchecks_two_apps(fleet: Path) -> None:
    site: sync.Site = sync.sites()["ep"]
    text: str = site.scenario.read_text(encoding="utf-8")
    assert text.startswith("# cherrymountain-site-ep scenario: the site `ep` alone. Generated by")
    assert list(apps(site)) == ["startup", *sync.SITE_PLANT_APPS, "vrouter", "soh"]
    for name in sync.SITE_PLANT_APPS:
        block: str = (site.phenix_dir / f"{name}.yaml").read_text(encoding="utf-8")
        assert "\n".join(sync.embed_lines(block)) + "\n" in text, name
    # The soh app has netcheck's tests of the conduits and plantgen's host checks.
    soh: dict[str, Any] = apps(site)["soh"]["metadata"]
    own: dict[str, Any] = yaml.safe_load((site.phenix_dir / "soh.yaml").read_text())["metadata"]
    assert soh["hostProcesses"] == own["hostProcesses"]
    assert all(probe in soh["testCustomReachability"] for probe in own["testCustomReachability"])
    assert len(soh["testCustomReachability"]) > len(own["testCustomReachability"])
    names: list[str] = [t["name"] for tests in soh["hostCustomTests"].values() for t in tests]
    assert any(name.startswith("blocked-") for name in names)
    assert "# sync:begin" not in text


def test_an_edited_scenario_is_stale_and_sync_writes_it_again(fleet: Path) -> None:
    site: sync.Site = sync.sites()["fc"]
    text: str = site.scenario.read_text(encoding="utf-8")
    site.scenario.write_text(text.replace("default: drop", "default: accept", 1))
    assert problems(site) == [
        "phenix-configs/scenario-site-fc.yml is not what sync.py writes for the site; run sync.py"
    ]
    assert problems(site, check=False) == []
    assert site.scenario.read_text(encoding="utf-8") == text


def test_a_changed_block_of_plantgen_reaches_the_scenario(fleet: Path) -> None:
    site: sync.Site = sync.sites()["fc"]
    block: Path = site.phenix_dir / "ntp.yaml"
    block.write_text(block.read_text().replace("client: chrony", "client: ntp"))
    assert len(problems(site)) == 1
    assert problems(site, check=False) == []
    clients: set[str] = {host["metadata"].get("client") for host in apps(site)["ntp"]["hosts"]} - {
        None
    }
    assert clients == {"ntp"}


def test_a_missing_or_unknown_block_is_named(fleet: Path) -> None:
    site: sync.Site = sync.sites()["fc"]
    shutil.copy(site.phenix_dir / "ntp.yaml", site.phenix_dir / "wireguard.yaml")
    with pytest.raises(ValueError, match=r"a site's scenario has no place for \['wireguard'\]"):
        sync.site_scenario(site)
    (site.phenix_dir / "wireguard.yaml").unlink()
    (site.phenix_dir / "helics.yaml").unlink()
    with pytest.raises(ValueError, match=r"has no block for \['helics'\]; run plantgen"):
        sync.site_scenario(site)


def test_a_site_that_does_not_fit_is_reported_not_written(fleet: Path) -> None:
    site: sync.Site = sync.sites()["fc"]
    (fleet / "wan" / "wan.yaml").unlink()
    with pytest.raises(ValueError, match="wan.yaml"):
        sync.site_scenario(site)


def test_a_changed_copy_is_stale_and_sync_copies_it_again(fleet: Path) -> None:
    site: sync.Site = sync.sites()["ep"]
    copy: Path = site.injects / "vrouter" / "cm-vyos-config.sh"
    source: Path = site.generated / "injects" / "vrouter" / "cm-vyos-config.sh"
    assert copy.read_bytes() == source.read_bytes()
    assert copy.stat().st_mode & 0o111 and source.stat().st_mode & 0o111
    copy.write_text(copy.read_text().replace("OT_SVC=10.22.30.13", "OT_SVC=10.20.30.13"))
    stale: str = (
        "phenix-injects/fleet/ep/vrouter/cm-vyos-config.sh differs from "
        "plant/generated/fleet/ep/injects/vrouter/cm-vyos-config.sh"
    )
    assert problems(site) == [stale]
    assert problems(site, check=False) == []
    assert copy.read_bytes() == source.read_bytes()
    # A copied script must stay a script.
    copy.chmod(0o644)
    assert problems(site) == [stale]
    assert problems(site, check=False) == []
    assert copy.stat().st_mode & 0o111


def test_a_copy_without_a_source_is_left_over(fleet: Path) -> None:
    site: sync.Site = sync.sites()["fc"]
    extra: Path = site.injects / "ot-svc" / "plant.hosts"
    extra.parent.mkdir()
    extra.write_text("10.21.10.40 fc-scada-fuxa\n")
    found: list[str] = problems(site)
    assert len(found) == 1 and "phenix-injects/fleet/fc/ot-svc/plant.hosts is left over" in found[0]
    assert problems(site, check=False) == []
    assert not extra.parent.exists()
    assert sorted(p.name for p in site.injects.iterdir()) == ["vrouter"]


def test_what_is_left_of_a_site_that_sites_yaml_lost(fleet: Path) -> None:
    found: dict[str, sync.Site] = sync.sites()
    assert sync.sync_site_leftovers(found, check=True) == []
    scenario: Path = fleet / "phenix-configs" / "scenario-site-xx.yml"
    shutil.copy(found["fc"].scenario, scenario)
    shutil.copytree(found["fc"].injects, fleet / "phenix-injects" / "fleet" / "xx")
    left: list[str] = sync.sync_site_leftovers(found, check=True)
    assert len(left) == 2 and all("plant/sites.yaml has no such site" in line for line in left)
    assert sync.sync_site_leftovers(found, check=False) == []
    assert not scenario.exists() and not (fleet / "phenix-injects" / "fleet" / "xx").exists()


def test_the_command_checks_the_sites() -> None:
    """`python sync.py --check` covers every site, and `--site` takes one."""
    assert sync.main(["--check"]) == 0
    assert sync.main(["--check", "--site", "fc"]) == 0
    assert sync.main(["--check", "--site", "zz"]) == 1
