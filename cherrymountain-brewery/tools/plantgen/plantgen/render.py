def modbus_master(
    plant: Plant, alloc: Allocation, plc: str, rios: list[str]
) -> list[dict[str, Any]]:
    """OpenPLC v4 ``modbus_master`` plugin config (runtime JSON schema)."""
    poll = plant.hosts[plc].poll_ms
    devices = []
    for rio in rios:
        host = plant.hosts[rio]
        mb = host.modbus or ModbusEndpoint()
        points = [
            {
                "fc": b.fc,
                "offset": str(b.start),
                "iec_location": str(b.iec),
                "len": b.count,
                "cycle_time_ms": poll,
                "error_handling": "keep-last-value",
            }
            for b in master_blocks(alloc, rio)
        ]
        devices.append(
            {
                "name": rio,
                "protocol": "MODBUS",
                "config": {
                    "type": "SLAVE",
                    "transport": "tcp",
                    "host": host.ip(mb.interface),
                    "port": mb.port,
                    "slave_id": mb.unit_id,
                    "timeout_ms": 1000,
                    "io_points": points,
                },
            }
        )
    return devices


def _v3_block(blocks: list[MasterBlock], fc: int, rio: str) -> tuple[int, int]:
    """(start, size) of the one block with ``fc``; v3 has one per kind."""
    found = [b for b in blocks if b.fc == fc]
    if len(found) > 1:
        raise PlantError(f"{rio}: OpenPLC v3 allows one FC{fc} block, not {len(found)}")
    return (found[0].start, found[0].count) if found else (0, 0)


def modbus_slave(plant: Plant, alloc: Allocation, plc: str) -> dict[str, Any]:
    """OpenPLC v4 ``modbus_slave`` plugin config with an explicit ``buffer_mapping``.

    The counts are the highest located index + 1 per image table, so the v4
    runtime clamps nothing and the segment start addresses (``%MW0`` at
    ``qw_count``) are the ones FUXA is generated with.
    """
    mb = plant.hosts[plc].modbus or ModbusEndpoint()
    return {
        "network_configuration": {"host": "0.0.0.0", "port": mb.port},
        "word_order": "high_word_first",
        "buffer_mapping": alloc.layouts[plc].buffer_mapping(),
    }


def mbconfig(plant: Plant, alloc: Allocation, plc: str, rios: list[str]) -> str:
    """OpenPLC v3 ``mbconfig.cfg`` (fallback; same IEC map as v4)."""
    poll = plant.hosts[plc].poll_ms
    lines = [
        f"# {HEADER.format(variant=plant.variant)}",
        "# OpenPLC v3 fallback: slave devices map to %IX100.0, %QX100.0, %IW100,",
        "# and %QW100, the same IEC locations as the v4 modbus_master config.",
        f'Num_Devices = "{len(rios)}"',
        f'Polling_Period = "{poll}"',
        'Timeout = "1000"',
    ]
    for i, rio in enumerate(rios):
        host = plant.hosts[rio]
        mb = host.modbus or ModbusEndpoint()
        blocks = master_blocks(alloc, rio)
        di, co, ir, hr, hrr = (
            _v3_block(blocks, fc, rio) for fc in (2, 15, 4, 16, READ_HOLDING_FC)
        )
        p = f"device{i}"
        lines += [
            f'{p}.name = "{rio}"',
            f'{p}.slave_id = "{mb.unit_id}"',
            f'{p}.protocol = "TCP"',
            f'{p}.address = "{host.ip(mb.interface)}"',
            f'{p}.IP_Port = "{mb.port}"',
            f'{p}.RTU_Baud_Rate = "115200"',
            f'{p}.RTU_Parity = "None"',
            f'{p}.RTU_Data_Bits = "8"',
            f'{p}.RTU_Stop_Bits = "1"',
            f'{p}.RTU_TX_Pause = "0"',
            f'{p}.Discrete_Inputs_Start = "{di[0]}"',
            f'{p}.Discrete_Inputs_Size = "{di[1]}"',
            f'{p}.Coils_Start = "{co[0]}"',
            f'{p}.Coils_Size = "{co[1]}"',
            f'{p}.Input_Registers_Start = "{ir[0]}"',
            f'{p}.Input_Registers_Size = "{ir[1]}"',
            f'{p}.Holding_Registers_Read_Start = "{hrr[0]}"',
            f'{p}.Holding_Registers_Read_Size = "{hrr[1]}"',
            f'{p}.Holding_Registers_Start = "{hr[0]}"',
            f'{p}.Holding_Registers_Size = "{hr[1]}"',
        ]
    return "\n".join(lines) + "\n"


def st_name(tag_name: str) -> str:
    """IEC identifier for a tag: dots become underscores."""
    return tag_name.replace(".", "_")


def located_vars(plant: Plant, alloc: Allocation, plc: str) -> str:
    """Structured Text located-variable declarations for the PLC program."""
    lines = [
        f"(* {HEADER.format(variant=plant.variant)} *)",
        "(* Analog values are raw registers: engineering value = raw / 10^scaling. *)",
        "(* RIO I/O is at %IX100.0 / %QX100.0 / %IW100 / %QW100 (v3 and v4 alike). *)",
        "(* PLC memory: bits from %QX0.0 (coils), words from %MW0 (holding register "
        "qw_count and up, see modbus_slave.json). *)",
        "VAR",
    ]
    for t in plant.tags:
        if t.plc != plc:
            continue
        a = alloc.tags[t.name]
        iec_type = ("INT" if t.signed else "UINT") if is_analog(t.type) else "BOOL"
        note = t.desc
        if is_analog(t.type):
            note += f", {t.units}, x{10**t.scaling}"
        lines.append(f"  {st_name(t.name)} AT {a.plc_iec} : {iec_type}; (* {note} *)")
    lines.append("END_VAR")
    return "\n".join(lines) + "\n"


